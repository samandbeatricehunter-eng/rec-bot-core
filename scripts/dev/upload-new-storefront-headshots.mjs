import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const artifactDir = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, "artifacts/new-storefront-headshots");
for (const line of fs.readFileSync(path.join(root, ".env"), "utf8").split(/\r?\n/)) {
  const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
  if (match && !process.env[match[1]]) process.env[match[1]] = match[2].trim().replace(/^['"]|['"]$/g, "");
}
const accountId = process.env.CLOUDFLARE_ACCOUNT_ID;
const apiToken = process.env.CLOUDFLARE_API_TOKEN;
const accountHash = process.env.CLOUDFLARE_ACCOUNT_HASH;
if (!accountId || !apiToken || !accountHash) throw new Error("Cloudflare Images credentials are missing.");

const input = JSON.parse(fs.readFileSync(path.join(root, "docs/legends/new-storefront-headshot-input.json"), "utf8"));
const licensePath = path.join(artifactDir, "licenses.csv");
function csvCells(line) {
  const cells = []; let value = ""; let quoted = false;
  for (let index = 0; index < line.length; index++) {
    const char = line[index];
    if (char === '"' && quoted && line[index + 1] === '"') { value += '"'; index++; }
    else if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) { cells.push(value); value = ""; }
    else value += char;
  }
  cells.push(value); return cells;
}
const licenses = new Map();
if (fs.existsSync(licensePath)) {
  const licenseRows = fs.readFileSync(licensePath, "utf8").replace(/^\uFEFF/, "").split(/\r?\n/);
  const header = csvCells(licenseRows.shift());
  for (const line of licenseRows.filter(Boolean)) {
    const cells = csvCells(line);
    const row = Object.fromEntries(header.map((key, index) => [key, cells[index] ?? ""]));
    licenses.set(row.filename, row);
  }
}

async function deleteExisting(id) {
  const response = await fetch(`https://api.cloudflare.com/client/v4/accounts/${accountId}/images/v1/${id}`, { method: "DELETE", headers: { Authorization: `Bearer ${apiToken}` } });
  if (!response.ok && response.status !== 404) throw new Error(`Could not replace ${id}: HTTP ${response.status}`);
}
async function upload(row) {
  const rights = licenses.get(row.file);
  const imagePath = path.join(artifactDir, "images", row.file);
  if (!fs.existsSync(imagePath) || fs.statSync(imagePath).size < 20_000 || rights?.rights_status === "missing_placeholder") {
    return { ...row, status: "missing", source: rights?.source_page ?? "" };
  }
  const bytes = fs.readFileSync(imagePath);
  const send = async () => {
    const form = new FormData();
    form.append("file", new Blob([bytes], { type: "image/png" }), row.file);
    form.append("id", row.cloudflare_id); form.append("requireSignedURLs", "false");
    form.append("metadata", JSON.stringify({ catalogName: row.name, position: row.position, source: rights?.source_page || rights?.source_image_url || "" }));
    return fetch(`https://api.cloudflare.com/client/v4/accounts/${accountId}/images/v1`, { method: "POST", headers: { Authorization: `Bearer ${apiToken}` }, body: form });
  };
  let response = await send();
  if (!response.ok) {
    const first = await response.clone().json().catch(() => null);
    if (first?.errors?.some((error) => /already exists/i.test(error.message ?? ""))) { await deleteExisting(row.cloudflare_id); response = await send(); }
  }
  const payload = await response.json();
  if (!response.ok || !payload.success) throw new Error(`${row.name}: ${payload.errors?.[0]?.message ?? `HTTP ${response.status}`}`);
  return { ...row, status: "uploaded", image_id: payload.result.id, photo_url: `https://imagedelivery.net/${accountHash}/${payload.result.id}/public`, source: rights?.source_page || rights?.source_image_url || "" };
}

const results = [];
for (let index = 0; index < input.length; index += 4) {
  const batch = await Promise.all(input.slice(index, index + 4).map(upload));
  results.push(...batch);
  console.log(`[${Math.min(index + 4, input.length)}/${input.length}] uploaded=${results.filter((row) => row.status === "uploaded").length} missing=${results.filter((row) => row.status === "missing").length}`);
}
const output = path.join(root, "docs/legends/new-storefront-headshot-uploads.json");
fs.writeFileSync(output, `${JSON.stringify(results, null, 2)}\n`);
const uploaded = results.filter((row) => row.status === "uploaded");
const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;
const migration = path.join(root, "supabase/migrations/20260908200000_attach_new_storefront_headshots.sql");
const values = uploaded.map((row) => `(${sql(row.name)},${sql(row.position)},${sql(row.photo_url)},${sql(row.source || "")})`).join(",\n");
fs.writeFileSync(migration, [
  "-- Generated by scripts/dev/upload-new-storefront-headshots.mjs after Cloudflare Images upload.",
  "with images(name, position, photo_url, source_url) as (values",
  values,
  ")",
  "update public.rec_legend_catalog as catalog",
  "set photo_url = images.photo_url",
  "from images",
  "where lower(catalog.name) = lower(images.name) and catalog.position = images.position;",
  "",
].join("\n"));
console.log(JSON.stringify({ output, migration, uploaded: uploaded.length, missing: results.filter((row) => row.status === "missing").length }, null, 2));
